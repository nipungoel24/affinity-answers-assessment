"""Run the queries in queries.sql against the public Rfam MySQL database.

Usage:
    python q2_sql_rfam/run_queries.py           # fast (~10 s): Q2.1/Q2.2 live; Q2.3/Q2.4 SQL,
                                                #   recorded page-9 rows and a live spot-check
    python q2_sql_rfam/run_queries.py --full    # every query live (~5 min), rewrites RESULTS.md
    python q2_sql_rfam/run_queries.py --full --only q2_1a_acacia_genus --stdout
"""

from __future__ import annotations

import argparse
import re
import sys
import time
from dataclasses import dataclass
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Optional, Sequence

import pymysql

HERE = Path(__file__).resolve().parent
SQL_FILE = HERE / "queries.sql"
RESULTS_FILE = HERE / "RESULTS.md"

RFAM = {
    "host": "mysql-rfam-public.ebi.ac.uk",
    "port": 4497,
    "user": "rfamro",
    "password": "",
    "database": "Rfam",
}

BLOCK_RE = re.compile(r"^-- name:\s*(\S+)\s*\n-- title:\s*(.+?)\s*\n(.*?;)", re.M | re.S)


@dataclass
class Query:
    name: str
    title: str
    sql: str


@dataclass
class Result:
    query: Query
    columns: list[str]
    rows: list[tuple[Any, ...]]
    seconds: float


def load_queries(path: Path = SQL_FILE) -> list[Query]:
    """Parse ``-- name:`` / ``-- title:`` blocks; each block ends at its first ';'."""
    text = path.read_text(encoding="utf-8")
    return [Query(m[1], m[2], m[3].strip()) for m in BLOCK_RE.finditer(text)]


def connect(read_timeout: int = 900) -> pymysql.connections.Connection:
    return pymysql.connect(**RFAM, connect_timeout=20, read_timeout=read_timeout, charset="utf8mb4")


def run(conn, query: Query) -> Result:
    start = time.perf_counter()
    with conn.cursor() as cur:
        cur.execute(query.sql)
        rows = list(cur.fetchall())
        columns = [d[0] for d in cur.description]
    return Result(query, columns, rows, time.perf_counter() - start)


def _fmt(value: Any) -> str:
    if isinstance(value, int):
        return f"{value:,}"
    return str(value).replace("|", "\\|")


def to_markdown_table(result: Result) -> str:
    cols = ["#"] + result.columns if len(result.rows) > 1 else result.columns
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for i, row in enumerate(result.rows, 1):
        cells = [_fmt(v) for v in row]
        if len(result.rows) > 1:
            cells.insert(0, str(i))
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


def _scalar(results: dict[str, Result], name: str) -> Optional[Any]:
    res = results.get(name)
    return res.rows[0][0] if res and res.rows else None


def summary(results: dict[str, Result]) -> list[str]:
    """Headline answers, so the exact numbers are at the top of RESULTS.md."""
    out = []
    a, b, c = (_scalar(results, n) for n in ("q2_1a_acacia_genus", "q2_1b_acacia_plants", "q2_1c_acacia_wildcard"))
    if a is not None:
        out.append(
            f"- **Q2.1 Acacia types: {a}** (genus match `species LIKE 'Acacia %'`). "
            f"Plant-clade reading: {b}; broad `'%Acacia%'` wildcard: {c}."
        )
    wheat = results.get("q2_2_longest_wheat")
    if wheat and wheat.rows:
        species, ncbi_id, acc, length = wheat.rows[0]
        out.append(
            f"- **Q2.2 Longest wheat sequence: {species}** - ncbi_id {ncbi_id}, "
            f"rfamseq_acc `{acc}`, {length:,} bp."
        )
    for name, label in (("q2_3_page9_significant", "is_significant = 1"), ("q2_3_page9_all_regions", "all regions")):
        res = results.get(name)
        if res:
            first = f"{res.rows[0][0]} .. {res.rows[-1][0]}" if res.rows else "no rows"
            out.append(f"- **Q2.3/Q2.4 page 9 ({label}):** {len(res.rows)} rows ({first}).")
    return out


def render(results: dict[str, Result]) -> str:
    now = datetime.now(timezone.utc).isoformat(timespec="seconds")
    parts = [
        "# Q2 - Rfam query results (live)",
        "",
        f"Generated by `python q2_sql_rfam/run_queries.py --full` at {now} against "
        f"`{RFAM['host']}:{RFAM['port']}/{RFAM['database']}`. SQL: [`queries.sql`](queries.sql).",
        "",
        "## Answers",
        "",
        *summary(results),
    ]
    for res in results.values():
        parts += [
            "",
            f"## {res.query.title}",
            "",
            f"`{res.query.name}` - {len(res.rows)} row(s) in {res.seconds:.1f}s",
            "",
            "```sql",
            res.query.sql,
            "```",
            "",
            to_markdown_table(res),
        ]
    return "\n".join(parts) + "\n"


HEAVY_PREFIX = "q2_3_"  # page-9 queries: one ~100 s scan of the 81M-row rfamseq table each
RECORDED_ROW_RE = re.compile(r"^\|(.*)\|\s*$")


def load_recorded(name: str, path: Path = RESULTS_FILE) -> tuple[Optional[str], list[str], list[list[str]]]:
    """Return (generated_at, header, rows) for one query's table in RESULTS.md."""
    if not path.exists():
        return None, [], []
    lines = path.read_text(encoding="utf-8").splitlines()
    stamp = next((m[1] for line in lines if (m := re.search(r" at (\S+) against", line))), None)
    try:
        start = next(i for i, line in enumerate(lines) if line.startswith(f"`{name}` - "))
    except StopIteration:
        return stamp, [], []
    table = []
    for line in lines[start + 1 :]:
        if line.startswith("## "):
            break
        if (m := RECORDED_ROW_RE.match(line)) and not set(line) <= set("|-"):
            table.append([cell.strip() for cell in m[1].split(" | ")])
    return stamp, (table[0] if table else []), table[1:]


def spot_check(conn, families: list[str], seq_acc: str, significant: bool) -> tuple[int, float]:
    """Count families with a hit on ``seq_acc`` (indexed lookup, ~2 s)."""
    sql = (
        "SELECT COUNT(DISTINCT fr.rfam_acc) FROM full_region fr "
        "WHERE fr.rfamseq_acc = %s AND fr.rfam_acc IN %s"
        + (" AND fr.is_significant = 1" if significant else "")
    )
    start = time.perf_counter()
    with conn.cursor() as cur:
        cur.execute(sql, (seq_acc, families))
        found = cur.fetchone()[0]
    return found, time.perf_counter() - start


def print_section(title: str, sql: str, table: str, note: str) -> None:
    print(f"\n=== {title}  [{note}]\n")
    print(sql)
    print()
    print(table)


def run_fast(conn, queries: list[Query]) -> None:
    results: dict[str, Result] = {}
    for q in queries:
        if q.name.startswith(HEAVY_PREFIX):
            continue
        results[q.name] = res = run(conn, q)
        print_section(q.title, q.sql, to_markdown_table(res), f"live, {res.seconds:.1f}s")

    wheat = results.get("q2_2_longest_wheat")
    for q in queries:
        if not q.name.startswith(HEAVY_PREFIX):
            continue
        stamp, header, rows = load_recorded(q.name)
        if not rows:
            print_section(q.title, q.sql, "(no recorded rows - run with --full)", "not run")
            continue
        recorded = Result(q, header[1:], [tuple(r[1:]) for r in rows], 0.0)
        print_section(q.title, q.sql, to_markdown_table(recorded), f"recorded by --full run at {stamp}")
        lengths = {r[-1] for r in rows}
        if wheat and wheat.rows and lengths == {f"{wheat.rows[0][3]:,}"}:
            seq_acc, length = wheat.rows[0][2], wheat.rows[0][3]
            families = [r[header.index("rfam_acc")] for r in rows]
            found, secs = spot_check(conn, families, seq_acc, "is_significant" in q.sql)
            print(
                f"\nlive spot-check: {found}/{len(families)} families have a hit on {seq_acc} "
                f"({length:,} bp), so each max_sequence_length >= {length:,}  [{secs:.1f}s]"
            )
    print("\nFull 81M-row scan for Q2.3/Q2.4: python q2_sql_rfam/run_queries.py --full  (~5 min)")


def main(argv: Optional[Sequence[str]] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--full", action="store_true", help="Run every query live and rewrite RESULTS.md")
    parser.add_argument("--only", nargs="+", metavar="NAME", help="With --full: run only these query names")
    parser.add_argument("--output", type=Path, default=RESULTS_FILE, help="With --full: markdown output path")
    parser.add_argument("--stdout", action="store_true", help="With --full: print markdown instead of writing")
    args = parser.parse_args(argv)
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")

    queries = load_queries()
    if args.only:
        missing = set(args.only) - {q.name for q in queries}
        if missing:
            parser.error(f"unknown query name(s): {', '.join(sorted(missing))}")
        queries = [q for q in queries if q.name in args.only]

    try:
        conn = connect()
    except pymysql.MySQLError as exc:
        print(f"[error] cannot reach Rfam MySQL: {exc}", file=sys.stderr)
        return 2

    with conn:
        if not args.full:
            print(f"Rfam live: {RFAM['host']}:{RFAM['port']}/{RFAM['database']}")
            run_fast(conn, queries)
            return 0
        results: dict[str, Result] = {}
        for q in queries:
            print(f"[*] {q.name} ...", file=sys.stderr, flush=True)
            results[q.name] = res = run(conn, q)
            print(f"    {len(res.rows)} row(s) in {res.seconds:.1f}s", file=sys.stderr)

    markdown = render(results)
    if args.stdout:
        sys.stdout.write(markdown)
    else:
        args.output.write_text(markdown, encoding="utf-8")
        print(f"[+] Wrote {args.output}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
